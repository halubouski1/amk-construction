#!/usr/bin/env python3
"""Build the HTML pages from src/ (npm run build:html, part of npm run build).

  src/<page>.html            → <page>.html          (src/index.html → index.html)
  src/<dir>/index.html       → <dir>/index.html     (clean URLs: /about/, /services/kitchen-remodeling/)

Macros in the sources:
  {{include NAME}}            the contents of src/partials/NAME.html
  {{include header|KEY}}      the header with the nav item data-nav="KEY" marked as the current page
  {{pic NAME|CLASS|SIZES|W|H|ALT|MODE}}
                              a <picture> for assets/images/NAME-<w>.webp(+avif) from tools/images.manifest.json;
                              MODE: lcp (eager + fetchpriority=high), eager, or empty (lazy)
All asset paths are root-absolute (/assets/…, /css/…, /js/…), so a page works at any depth.
Generated pages start with a "Generated by" comment. Edit src/, never the output.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'src'
PARTIALS = SRC / 'partials'
MANIFEST = json.loads((ROOT / 'tools' / 'images.manifest.json').read_text())


def srcset(name, ext):
    return ', '.join(f'/assets/images/{name}-{w}.{ext} {w}w' for w in MANIFEST[name]['widths'])


def pic(name, cls='', sizes='', w='', h='', alt='', mode=''):
    if name not in MANIFEST:
        raise SystemExit(f'pic: unknown image "{name}" (add it to tools/images.config.json and run npm run build:images)')
    largest = MANIFEST[name]['widths'][-1]
    attrs = [f'class="{cls}"'] if cls else []
    attrs += [f'src="/assets/images/{name}-{largest}.webp"', f'srcset="{srcset(name, "webp")}"', f'sizes="{sizes}"',
              f'width="{w}"', f'height="{h}"', f'alt="{html.escape(alt)}"']
    if mode == 'lcp':
        attrs.append('fetchpriority="high"')
    elif mode != 'eager':
        attrs += ['loading="lazy"', 'decoding="async"']
    img = '<img ' + ' '.join(attrs) + '>'
    if MANIFEST[name]['avif']:
        return f'<picture><source type="image/avif" srcset="{srcset(name, "avif")}" sizes="{sizes}">{img}</picture>'
    return f'<picture>{img}</picture>'


def include(name, current=''):
    text = (PARTIALS / f'{name}.html').read_text().rstrip('\n').lstrip(' ')
    if current:
        marker = f'data-nav="{current}"'
        if marker not in text:
            raise SystemExit(f'include {name}: no element with {marker}')
        text = text.replace(marker, f'{marker} aria-current="page"')
    return expand(text)


MACROS = {'include': include, 'pic': pic}
MACRO = re.compile(r'\{\{(\w+) ([^}]*)\}\}')


def expand(text):
    return MACRO.sub(lambda m: MACROS[m.group(1)](*m.group(2).split('|')), text)


def main():
    pages = sorted(p for p in SRC.rglob('*.html') if PARTIALS not in p.parents)
    for src in pages:
        rel = src.relative_to(SRC)
        out = ROOT / rel
        body = expand(src.read_text())
        if '{{' in body:
            raise SystemExit(f'{rel}: unexpanded macro')
        banner = f'<!-- Generated by tools/build-html.py from src/{rel.as_posix()}. Do not edit. -->\n'
        body = body.replace('<!doctype html>\n', '<!doctype html>\n' + banner, 1)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(body)
        print(f'src/{rel.as_posix()} → {rel.as_posix()}')


if __name__ == '__main__':
    main()
