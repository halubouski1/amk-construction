#!/usr/bin/env python3
"""Expand tools/compact.tpl.css into css/media.css (compact layout, ≤1279px).

m(N) becomes calc(Npx * var(--m)): the Figma mobile value (360 frame) times the
per-breakpoint factor --m. The result replaces everything between
    /* compact:generated:start */ … /* compact:generated:end */
in css/media.css. Edit the template, never the generated block.

Run from the project root:  python3 tools/build-compact.py   (part of npm run build:css)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TPL = ROOT / 'tools' / 'compact.tpl.css'
MEDIA = ROOT / 'css' / 'media.css'
START = '/* compact:generated:start */'
END = '/* compact:generated:end */'
M = re.compile(r'\bm\((-?\d*\.?\d+)\)')


def expand(css):
    return M.sub(lambda match: 'calc(%spx * var(--m))' % match.group(1), css)


def main():
    body = expand(TPL.read_text())
    if 'm(' in re.sub(r'/\*.*?\*/', '', body, flags=re.S).replace('calc(', '').replace('var(--m)', ''):
        leftover = [l for l in body.splitlines() if re.search(r'\bm\(', l)]
        if leftover:
            raise SystemExit('unexpanded m(): %s' % leftover[:3])
    media = MEDIA.read_text()
    start, end = media.find(START), media.find(END)
    if start == -1 or end == -1:
        raise SystemExit('compact markers not found in css/media.css')
    banner = '/* Generated by tools/build-compact.py from tools/compact.tpl.css. Do not edit by hand. */\n'
    MEDIA.write_text(media[:start + len(START)] + '\n' + banner + body.strip() + '\n' + media[end:])
    print('compact block regenerated')


if __name__ == '__main__':
    main()
